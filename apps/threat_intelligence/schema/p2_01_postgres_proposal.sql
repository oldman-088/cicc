-- PROPOSAL ONLY: requires host review and migration approval. No automatic deployment.
BEGIN;
CREATE TABLE ti_relationship_audit (
	event_id UUID NOT NULL,
	tenant_id VARCHAR(256) NOT NULL,
	actor VARCHAR(256) NOT NULL,
	operation VARCHAR(64) NOT NULL,
	resource_id UUID,
	outcome VARCHAR(32) NOT NULL,
	correlation_id UUID NOT NULL,
	occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
	PRIMARY KEY (event_id)
);

CREATE INDEX ix_ti_audit_tenant_time ON ti_relationship_audit (tenant_id, occurred_at);
CREATE TABLE ti_relationship_entity (
	tenant_id VARCHAR(256) NOT NULL,
	entity_type VARCHAR(256) NOT NULL,
	entity_id VARCHAR(256) NOT NULL,
	PRIMARY KEY (tenant_id, entity_type, entity_id)
);

CREATE TABLE ti_relationship_record (
	sequence BIGINT GENERATED BY DEFAULT AS IDENTITY,
	tenant_id VARCHAR(256) NOT NULL,
	relationship_id UUID NOT NULL,
	source_type VARCHAR(256) NOT NULL,
	source_id VARCHAR(256) NOT NULL,
	target_type VARCHAR(256) NOT NULL,
	target_id VARCHAR(256) NOT NULL,
	relationship_type VARCHAR(32) NOT NULL,
	fingerprint VARCHAR(64) NOT NULL,
	record JSONB NOT NULL,
	PRIMARY KEY (sequence),
	CONSTRAINT uq_ti_relationship_identity UNIQUE (tenant_id, relationship_id),
	CONSTRAINT uq_ti_relationship_fingerprint UNIQUE (tenant_id, fingerprint),
	CONSTRAINT uq_ti_relationship_identity_fingerprint UNIQUE (tenant_id, relationship_id, fingerprint),
	FOREIGN KEY(tenant_id, source_type, source_id) REFERENCES ti_relationship_entity (tenant_id, entity_type, entity_id),
	FOREIGN KEY(tenant_id, target_type, target_id) REFERENCES ti_relationship_entity (tenant_id, entity_type, entity_id)
);

CREATE INDEX ix_ti_rel_source ON ti_relationship_record (tenant_id, source_type, source_id, sequence);
CREATE INDEX ix_ti_rel_target ON ti_relationship_record (tenant_id, target_type, target_id, sequence);
CREATE INDEX ix_ti_rel_type ON ti_relationship_record (tenant_id, relationship_type, sequence);
CREATE TABLE ti_relationship_idempotency (
	tenant_id VARCHAR(256) NOT NULL,
	key VARCHAR(128) NOT NULL,
	fingerprint VARCHAR(64) NOT NULL,
	relationship_id UUID NOT NULL,
	PRIMARY KEY (tenant_id, key),
	FOREIGN KEY(tenant_id, relationship_id, fingerprint) REFERENCES ti_relationship_record (tenant_id, relationship_id, fingerprint)
);

COMMIT;
