function formatTimestamp(value: string | null, locale: Locale, fallback: string): string {
  if (value === null) return fallback;
  const parsed = new Date(value);
  if (!Number.isFinite(parsed.getTime())) return value;
  return new Intl.DateTimeFormat(locale, { dateStyle: "medium", timeStyle: "short" }).format(parsed);
}

function statusTone(value: string): string {
  const normalized = value.toLowerCase();
  if (["ok", "healthy", "online", "connected"].includes(normalized)) return styles.toneSuccess;
  if (["degraded", "warning", "stale", "maintenance"].includes(normalized)) return styles.toneWarning;
  if (["down", "error", "failed", "unavailable", "not_configured"].includes(normalized)) return styles.toneDanger;
  return styles.toneNeutral;
}

function OperationsSummary({ data, locale, text }: { data: OpsOverview; locale: Locale; text: ReadinessMessages }) {
  const cacheText = data.cached === true ? text.cached : data.cached === false ? text.notCached : text.cacheUnknown;
  return (
    <div className={styles.summary}>
      <dl className={styles.dataList}>
        <div>
          <dt>{text.reportedStatus}</dt>
          <dd><span className={`${styles.statusBadge} ${statusTone(data.overall_status)}`}><bdi dir="auto">{data.overall_status}</bdi></span></dd>
        </div>
        <div>
          <dt>{text.generatedAt}</dt>
          <dd><time dateTime={data.generated_at}>{formatTimestamp(data.generated_at, locale, "—")}</time></dd>
        </div>
        <div>
          <dt>{text.sourceLabel}</dt>
          <dd><code><bdi dir="ltr">{data.data_source}</bdi></code></dd>
        </div>
        <div>
          <dt>{text.cacheState}</dt>
          <dd>{cacheText}{data.cache_age_s === null ? "" : ` · ${text.cacheAge}: ${new Intl.NumberFormat(locale, { maximumFractionDigits: 1 }).format(data.cache_age_s)}s`}</dd>
        </div>
      </dl>
      <p className={styles.caveat}>{text.sourceDisclaimer}</p>
    </div>
  );
}

function CoordinationSummary({ data, locale, text }: { data: CoordinationHealth; locale: Locale; text: ReadinessMessages }) {
  const reasonsId = useId().replaceAll(":", "");
  return (
    <div className={styles.summary}>
      <dl className={styles.dataList}>
        <div>
          <dt>{text.reportedStatus}</dt>
          <dd><span className={`${styles.statusBadge} ${statusTone(data.overall)}`}><bdi dir="auto">{text.healthStatus[data.overall]}</bdi></span></dd>
        </div>
        <div>
          <dt>{text.apiCheckAt}</dt>
          <dd><time dateTime={data.last_operations.checked_at ?? data.at ?? ""}>{formatTimestamp(data.last_operations.checked_at ?? data.at, locale, "—")}</time></dd>
        </div>
      </dl>
      <div className={styles.detailGroup}>
        <h3>{text.components}</h3>
        {data.components.length === 0 ? <p className={styles.quiet}>{text.noComponents}</p> : (
          <ul className={styles.providerList}>
            {data.components.map((component) => (
              <li key={component.key}>
                <div className={styles.listHeading}>
                  <bdi dir="auto">{component.key}</bdi>
                  <span className={`${styles.miniStatus} ${statusTone(component.status)}`}><bdi dir="auto">{text.healthStatus[component.status]}</bdi></span>
                </div>
                {component.detail && <p><bdi dir="auto">{component.detail}</bdi></p>}
                {component.reasons.length > 0 && <ul className={styles.reasonList}>{component.reasons.map((reason, index) => <li key={`${component.key}-${index}`}><bdi dir="auto">{reason}</bdi></li>)}</ul>}
              </li>
            ))}
          </ul>
        )}
      </div>
      <div className={styles.detailGroup}>
        <h3 id={reasonsId}>{text.reasons}</h3>
        {data.reasons.length === 0 ? <p className={styles.quiet}>{text.noReasons}</p> : (
          <ul className={styles.reasonList} aria-labelledby={reasonsId}>
            {data.reasons.map((reason, index) => <li key={`${index}-${reason}`}><bdi dir="auto">{reason}</bdi></li>)}
          </ul>
        )}
      </div>
      <p className={styles.caveat}>{text.onDemandWarning} <span>{text.apiNote}: <bdi dir="auto">{data.last_operations.note}</bdi></span></p>
    </div>
  );
}

export function BetaReadinessPanel() {
  const locale = useCiccLocale()?.locale ?? "en";
  const text = messages[locale];
  const id = useId().replaceAll(":", "");
  const operations = useIntegrationResource(integrationEndpoints.opsOverview, parseOpsOverview);
  const coordination = useIntegrationResource(integrationEndpoints.coordinationHealth, parseCoordinationHealth);
  const refreshing = operations.state.status === "loading" || coordination.state.status === "loading";

  return (
    <section className={styles.panel} aria-labelledby={`${id}-title`} data-testid="beta-readiness-panel" lang={locale} dir={locale === "en" ? "ltr" : "rtl"}>
      <header className={styles.header}>
        <div>
          <p className={styles.eyebrow}>{text.eyebrow}</p>
          <h2 id={`${id}-title`}>{text.title}</h2>
          <p className={styles.intro}>{text.intro}</p>
        </div>
        <button
          className={styles.refreshButton}
          type="button"
          onClick={() => { operations.refresh(); coordination.refresh(); }}
          disabled={refreshing}
          aria-busy={refreshing}
        >
          {refreshing ? text.refreshing : text.refresh}
        </button>
      </header>

      <h3 className={styles.sectionTitle}>{text.checks}</h3>
      <div className={styles.checkGrid} aria-busy={refreshing}>
        <ResourcePanel title={text.operations} state={operations.state} onRefresh={operations.refresh}>
          {(data) => <OperationsSummary data={data} locale={locale} text={text} />}
        </ResourcePanel>
        <ResourcePanel title={text.coordination} state={coordination.state} onRefresh={coordination.refresh}>
          {(data) => <CoordinationSummary data={data} locale={locale} text={text} />}
        </ResourcePanel>
      </div>

      <section className={styles.contracts} aria-labelledby={`${id}-contracts-title`}>
        <div className={styles.sectionHeading}>
          <h3 id={`${id}-contracts-title`}>{text.contractTitle}</h3>
          <p>{text.contractIntro}</p>
        </div>
        <div className={styles.contractGrid}>
          {betaIntegrationContracts.map((contract) => {
            const destination = contract.id === "domain-lifecycle" ? "coordination"
              : contract.id === "threat-intelligence" ? "threatIntelligence"
                : "vulnerabilityIntelligence";
            const href = contract.id === "domain-lifecycle" ? "/coordination"
              : contract.id === "threat-intelligence" ? "/threat-intelligence"
                : "/vulnerability-intelligence";
            return (
              <article className={styles.contractCard} key={contract.id}>
                <div className={styles.contractTopline}>
                  <span className={styles.pendingBadge}>{text.contractBadge}</span>
                  <span className={styles.ownerLabel}>{contract.owner}</span>
                </div>
                <h4>{text.contractTitles[contract.id]}</h4>
                <p className={styles.contractStatus}>{text.contractStatuses[contract.id]}</p>
                <p>{text.contractDetails[contract.id]}</p>
                <p className={styles.evidence}>{text.evidenceOnly} · {contract.sourceDocument}</p>
                <Link href={href} className={styles.moduleLink}>{text.openPage[destination]} <span aria-hidden="true">↗</span></Link>
              </article>
            );
          })}
        </div>
      </section>
    </section>
  );
}
